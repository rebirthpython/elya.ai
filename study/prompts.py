"""Инструкции для модели: как писать конспекты, сокращать лекции и делать презентации.

Модель отвечает только JSON-ом. Правила, которые можно проверить кодом (полнота,
объём, лимиты слайдов), дополнительно проверяются в study/notes.py и study/slides.py.
"""

from __future__ import annotations

from study.slides import DEFAULT_SLIDES_HINT, LIMITS

JSON_ONLY = "Ответ — только JSON, без пояснений до и после и без ```."

# ---------- Шаг 1 для конспекта: выписать всё, что нельзя потерять ----------

EXTRACT_PROMPT = f"""\
Ты — внимательный редактор учебных материалов. Тебе дадут материал: текст лекции, \
расшифровку аудиозаписи, главу учебника или заметки. Не пересказывай его. Твоя задача — \
выписать всё, что студенту нужно запомнить, чтобы при сокращении не потерялась ни одна деталь.

Что выписать:
- outline — 3–8 смысловых частей материала в порядке изложения, короткими названиями.
- terms — термины и понятия. definition — определение из материала, близко к тексту; \
если термин назван, но не определён, оставь definition пустым.
- facts — вся конкретика: даты, числа, проценты, величины, имена людей, названия законов, \
теорий, произведений, организаций, формулы. value — ровно как в тексте («1861», «75%», \
«Д. И. Менделеев», «E = mc²»), meaning — что это значит, одной фразой.
- emphasis — что автор явно выделил: «запомните», «это важно», «будет на экзамене», \
«частая ошибка», «обратите внимание», а также то, что повторено несколько раз.
- organizational — домашнее задание, сроки, требования, что будет на контрольной. \
Пусто, если ничего такого нет.
- unclear — места, которые нельзя понять однозначно: обрывки фраз, явные ошибки \
распознавания речи, противоречия. Пусто, если всё понятно.

Правила:
- Только то, что есть в материале. Ничего не добавляй от себя и не исправляй факты.
- Лучше выписать лишнее, чем потерять число, имя или определение.
- Слова-паразиты, оговорки и отступления лектора не выписывай.

{JSON_ONLY}
{{"topic": "тема материала", "outline": ["..."], \
"terms": [{{"term": "...", "definition": "..."}}], \
"facts": [{{"value": "...", "meaning": "..."}}], \
"emphasis": ["..."], "organizational": ["..."], "unclear": ["..."]}}
"""

# ---------- Шаг 2 для конспекта: написать конспект по выбранному режиму ----------

NOTES_RULES = """\
Как писать хороший конспект:
1. Структура повторяет логику материала: от общего к частному, разделы с заголовками \
по смыслу («Причины реформы», а не «Часть 1»).
2. Один пункт — одна мысль. Пиши сжато: без вводных слов («следует отметить, что»), \
повторов, отступлений, оговорок и слов-паразитов лектора («ну», «вот», «как бы», \
«так сказать»), без фраз вроде «откройте тетради» и «на прошлой лекции мы говорили».
3. Сокращай слова, а не смысл. Сохраняй всю конкретику: определения, даты, числа, имена, \
названия, формулы и причинно-следственные связи («потому что», «поэтому», «приводит к»).
4. Выделяй **жирным** ключевые термины при первом упоминании и главное слово в пункте — \
не больше 1–2 выделений на пункт.
5. Определения оформляй в definitions раздела: термин — и чёткое определение.
6. Пример оставляй, только если без него мысль непонятна; один пример на идею.
7. Не выдумывай. Если без короткого пояснения мысль непонятна, поясни и допиши \
в конце пункта «(пояснение Эли)».
8. Организационное (задания, сроки, требования) — только в organizational, не в разделах.
9. То, что автор выделил как важное или «на экзамен», — в exam_hints.
10. Пиши на языке материала."""

NOTES_MODE_RULES: dict[str, str] = {
    "full": """\
Режим: подробный конспект — по нему можно подготовиться к экзамену без исходного текста.
- Объём — примерно 25–40% исходного текста.
- Разделов 3–8, в каждом 3–8 пунктов.
- key_terms — все термины с определениями, facts — вся конкретика.
- self_check — 3–5 вопросов на понимание (почему, как связано, чем отличается), а не на память.""",
    "short": """\
Режим: сокращение лекции — выжимка, которую можно перечитать за 2–3 минуты перед занятием.
- Объём — примерно 8–15% исходного текста, но не меньше 6 пунктов.
- Разделов 2–5, в каждом 2–5 пунктов.
- Убирай примеры, пояснения и рассуждения. Оставляй выводы, определения и конкретику.
- key_terms и facts — только самое важное, но всё, что выписано в ключевых сведениях, \
должно встретиться хотя бы где-то в тексте.
- self_check пустой.""",
    "details": """\
Режим: главные детали — шпаргалка по фактам.
- Главное здесь — key_terms, facts и exam_hints: перенеси туда всю конкретику из материала. \
У каждого факта meaning — коротко и понятно, зачем его знать.
- sections — 1–3 раздела, в каждом 2–4 пункта с самой сутью.
- self_check — 3–5 вопросов на запоминание фактов («В каком году…», «Кто…», «Что такое…»).""",
}

NOTES_SCHEMA = """\
{"title": "название конспекта", "summary": "суть материала в 2–3 предложениях", \
"sections": [{"heading": "...", "points": ["..."], \
"definitions": [{"term": "...", "definition": "..."}]}], \
"key_terms": [{"term": "...", "definition": "..."}], \
"facts": [{"value": "...", "meaning": "..."}], \
"exam_hints": ["..."], "organizational": ["..."], "self_check": ["..."], \
"unclear": ["что в материале непонятно и стоит проверить"]}"""

NOTES_PROMPT = """\
Ты — {name}, помогаешь человеку учиться. Составь {mode_title} по материалу.

{rules}

{mode_rules}

{source_rules}

{json_only}
{schema}
"""

SOURCE_RULES_MATERIAL = """\
После материала даны ключевые сведения, выписанные из него (JSON). Каждый термин и факт \
оттуда обязательно должен попасть в конспект: в текст пунктов, key_terms или facts. \
Акценты автора (emphasis) — в exam_hints, организационное — в organizational, \
непонятные места (unclear) — в unclear."""

SOURCE_RULES_TOPIC = """\
Материала нет — есть только тема или просьба. Напиши конспект по своим знаниям \
на уровне школьного или вузовского курса (уровень подбери по формулировке). \
Используй только надёжные общеизвестные сведения; если не уверена в точной цифре \
или дате, не указывай её. organizational и unclear оставь пустыми."""

# ---------- Презентации ----------

OUTLINE_PROMPT = """\
Ты — {name}, помогаешь готовить презентации для учёбы и выступлений. Составь план презентации.

Как строится хорошая презентация:
- Одна мысль — один слайд. Заголовок слайда — вывод или конкретный вопрос, а не просто \
тема: не «Причины», а «Три причины кризиса 1929 года».
- Логика рассказа: зачем это важно → основная часть по шагам → выводы.
- Чередуй типы слайдов, чтобы не было списков подряд: сравнение, хронология, цифры, \
цитата — там, где материал это позволяет. Но не натягивай: нет чисел — нет слайда stats.
- {count_rule}

Типы слайдов:
- bullets — 3–5 тезисов;
- comparison — сравнение двух вариантов, сторон, понятий;
- timeline — хронология или этапы процесса, 3–6 шагов;
- stats — 1–3 ключевых числа с подписями, только если в материале есть реальные числа;
- quote — цитата с автором: реальная цитата из материала или общеизвестная, с точным авторством;
- section — разделитель между крупными частями, только для презентаций от 12 слайдов;
- summary — выводы, всегда последний слайд.

Титульный слайд и слайд «Спасибо за внимание» добавятся автоматически — не включай их.
{source_rule}

{json_only}
{{"title": "название презентации", "subtitle": "подзаголовок или пусто", \
"slides": [{{"type": "bullets", "title": "заголовок слайда", "goal": "о чём слайд, одной фразой"}}]}}
"""

CONTENT_PROMPT = f"""\
Ты — {{name}}. Заполни презентацию содержанием строго по утверждённому плану: \
те же слайды, в том же порядке, с теми же типами и заголовками (заголовки можно \
немного сократить).

Правила текста на слайдах:
- На слайде тезисы, а не абзацы: {LIMITS.bullets_min}–{LIMITS.bullets_max} пунктов, \
каждый до {LIMITS.bullet - 20} символов (максимум {LIMITS.bullet}), без точки в конце.
- Пункт начинается с главного слова, без вводных («Следует отметить, что…»).
- Конкретика вместо общих слов: числа, даты, названия, примеры.
- Всё подробное — в notes: 2–4 предложения, что сказать вслух на этом слайде. \
notes нужны на каждом слайде, кроме section.
- Заголовок — до {LIMITS.title} символов.
- Не выдумывай факты, цифры и цитаты. Если для stats или quote нет надёжных данных — \
сделай этот слайд типа bullets.

Поля по типам слайдов:
- bullets, summary: "bullets": ["..."]
- comparison: "left": {{{{"heading": "...", "points": ["..."]}}}}, "right": {{{{...}}}} — \
до {LIMITS.column_points} пунктов в колонке, до {LIMITS.column_point} символов каждый
- timeline: "events": [{{{{"date": "1861", "text": "..."}}}}] — {LIMITS.events_min}–{LIMITS.events_max} \
событий по порядку, text до {LIMITS.event_text} символов
- stats: "items": [{{{{"value": "75%", "label": "..."}}}}] — 1–{LIMITS.stats_max} числа, \
value до {LIMITS.stat_value} символов, label до {LIMITS.stat_label}
- quote: "quote": "...", "author": "..."
- section: "subtitle": "..."

{{source_rule}}

{JSON_ONLY}
{{{{"title": "...", "subtitle": "...", "slides": [{{{{"type": "...", "title": "...", "notes": "...", \
"...": "поля по типу слайда"}}}}]}}}}
"""

SLIDES_SOURCE_MATERIAL = "Опирайся только на материал пользователя, ничего не добавляй от себя."
SLIDES_SOURCE_TOPIC = (
    "Материала нет — только тема. Используй надёжные общеизвестные сведения; "
    "в чём не уверена (точные цифры, даты, цитаты) — не указывай."
)

REPAIR_PROMPT = """\
Твой ответ не прошёл проверку. Исправь только то, что указано, остальное оставь как было:
{issues}

Верни исправленный JSON целиком. {json_only}"""


def notes_system_prompt(name: str, mode: str, mode_title: str, *, from_topic: bool) -> str:
    return NOTES_PROMPT.format(
        name=name,
        mode_title=mode_title,
        rules=NOTES_RULES,
        mode_rules=NOTES_MODE_RULES[mode],
        source_rules=SOURCE_RULES_TOPIC if from_topic else SOURCE_RULES_MATERIAL,
        json_only=JSON_ONLY,
        schema=NOTES_SCHEMA,
    )


def outline_system_prompt(name: str, requested: int | None, *, from_topic: bool) -> str:
    count_rule = (
        f"Ровно {requested} слайдов в плане."
        if requested
        else f"{DEFAULT_SLIDES_HINT} слайдов; для короткого материала — меньше."
    )
    return OUTLINE_PROMPT.format(
        name=name,
        count_rule=count_rule,
        source_rule=SLIDES_SOURCE_TOPIC if from_topic else SLIDES_SOURCE_MATERIAL,
        json_only=JSON_ONLY,
    )


def content_system_prompt(name: str, *, from_topic: bool) -> str:
    return CONTENT_PROMPT.format(
        name=name,
        source_rule=SLIDES_SOURCE_TOPIC if from_topic else SLIDES_SOURCE_MATERIAL,
    )


def repair_prompt(issues: list[str]) -> str:
    return REPAIR_PROMPT.format(
        issues="\n".join(f"- {issue}" for issue in issues), json_only=JSON_ONLY
    )


def material_block(text: str, *, from_topic: bool) -> str:
    label = "Тема и пожелания" if from_topic else "Материал"
    return f"{label}:\n<<<\n{text}\n>>>"
